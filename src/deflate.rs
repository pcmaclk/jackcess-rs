/// zlib's `pending_buf` + `bi_buf`: the bit stream of the deflate blocks.
///
/// zlib flushes the bit buffer into `pending_buf` whenever `flush_pending` is
/// called, but it never aligns except in `bi_windup`, so emitting the bits only
/// when the 16 bit buffer overflows or at `bi_windup` produces exactly the same
/// byte stream.
struct BitWriter {
    out: Vec<u8>,
    buf: u16,
    valid: u32,
}

impl BitWriter {
    fn new() -> BitWriter {
        BitWriter {
            out: Vec::new(),
            buf: 0,
            valid: 0,
        }
    }

    fn put_byte(&mut self, b: u8) {
        self.out.push(b);
    }

    fn put_short(&mut self, w: u16) {
        self.out.push(w as u8);
        self.out.push((w >> 8) as u8);
    }

    /// `send_bits` (Buf_size == 16).
    fn send_bits(&mut self, value: u16, length: u32) {
        if self.valid > 16 - length {
            let v = (self.buf as u32) | ((value as u32) << self.valid);
            self.put_short(v as u16);
            self.buf = ((value as u32) >> (16 - self.valid)) as u16;
            self.valid = self.valid + length - 16;
        } else {
            let v = (self.buf as u32) | ((value as u32) << self.valid);
            self.buf = v as u16;
            self.valid += length;
        }
    }

    fn send_code(&mut self, tree: &[CtData], code: usize) {
        let node = tree[code];
        self.send_bits(node.code, node.len as u32);
    }

    /// `bi_windup`: flush the bit buffer and align on a byte boundary.
    fn bi_windup(&mut self) {
        if self.valid > 8 {
            self.put_short(self.buf);
        } else if self.valid > 0 {
            self.put_byte(self.buf as u8);
        }
        self.buf = 0;
        self.valid = 0;
    }
}

