/// One node of a Huffman tree.  zlib overlays `freq`/`code` and `dad`/`len` in
/// a union; separate fields behave identically because the two halves are never
/// live at the same time.
#[derive(Clone, Copy, Default)]
struct CtData {
    freq: u16,
    code: u16,
    dad: u16,
    len: u16,
}

/// The constant tables of `tr_static_init` plus the static trees.
struct StaticTables {
    static_ltree: [CtData; L_CODES + 2],
    static_dtree: [CtData; D_CODES],
    length_code: [u8; 256],
    dist_code: [u8; 512],
    base_length: [u16; LENGTH_CODES],
    base_dist: [u16; D_CODES],
}

impl StaticTables {
    /// `d_code(dist)`.
    fn d_code(&self, dist: usize) -> usize {
        if dist < 256 {
            self.dist_code[dist] as usize
        } else {
            self.dist_code[256 + (dist >> 7)] as usize
        }
    }
}

fn static_tables() -> &'static StaticTables {
    static TABLES: OnceLock<StaticTables> = OnceLock::new();
    TABLES.get_or_init(|| {
        let mut t = StaticTables {
            static_ltree: [CtData::default(); L_CODES + 2],
            static_dtree: [CtData::default(); D_CODES],
            length_code: [0; 256],
            dist_code: [0; 512],
            base_length: [0; LENGTH_CODES],
            base_dist: [0; D_CODES],
        };

        // map lengths (0..255) to length codes (0..28)
        let mut length = 0usize;
        let mut code = 0usize;
        while code < LENGTH_CODES - 1 {
            t.base_length[code] = length as u16;
            for _ in 0..(1usize << EXTRA_LBITS[code]) {
                t.length_code[length] = code as u8;
                length += 1;
            }
            code += 1;
        }
        // length 255 (match length 258) has the better code 285
        t.length_code[length - 1] = code as u8;

        // map distances (0..32K) to distance codes (0..29)
        let mut dist = 0usize;
        for code in 0..16 {
            t.base_dist[code] = dist as u16;
            for _ in 0..(1usize << EXTRA_DBITS[code]) {
                t.dist_code[dist] = code as u8;
                dist += 1;
            }
        }
        dist >>= 7;
        for code in 16..D_CODES {
            t.base_dist[code] = (dist << 7) as u16;
            for _ in 0..(1usize << (EXTRA_DBITS[code] - 7)) {
                t.dist_code[256 + dist] = code as u8;
                dist += 1;
            }
        }

        // static literal/length tree
        let mut bl_count = [0u16; MAX_BITS + 1];
        let mut n = 0usize;
        while n <= 143 {
            t.static_ltree[n].len = 8;
            bl_count[8] += 1;
            n += 1;
        }
        while n <= 255 {
            t.static_ltree[n].len = 9;
            bl_count[9] += 1;
            n += 1;
        }
        while n <= 279 {
            t.static_ltree[n].len = 7;
            bl_count[7] += 1;
            n += 1;
        }
        while n <= 287 {
            t.static_ltree[n].len = 8;
            bl_count[8] += 1;
            n += 1;
        }
        gen_codes(&mut t.static_ltree, L_CODES + 1, &bl_count);

        // static distance tree: five bits, bit reversed codes
        for (n, entry) in t.static_dtree.iter_mut().enumerate() {
            entry.len = 5;
            entry.code = bi_reverse(n as u32, 5) as u16;
        }
        t
    })
}

/// `bi_reverse`: reverse the first `len` bits of `code`.
fn bi_reverse(code: u32, len: u32) -> u32 {
    let mut res = 0u32;
    let mut code = code;
    let mut len = len;
    loop {
        res |= code & 1;
        code >>= 1;
        res <<= 1;
        len -= 1;
        if len == 0 {
            break;
        }
    }
    res >> 1
}

/// `gen_codes`: generate the canonical codes for the given bit lengths.
fn gen_codes(tree: &mut [CtData], max_code: usize, bl_count: &[u16; MAX_BITS + 1]) {
    let mut next_code = [0u16; MAX_BITS + 1];
    let mut code = 0u32;
    for bits in 1..=MAX_BITS {
        code = (code + bl_count[bits - 1] as u32) << 1;
        next_code[bits] = code as u16;
    }
    // `for (n = 0; n <= max_code; n++)`: `max_code` is always an index into
    // `tree` (every tree is sized above its `elems`), so the slice covers it.
    for node in tree.iter_mut().take(max_code + 1) {
        let len = node.len;
        if len == 0 {
            continue;
        }
        node.code = bi_reverse(next_code[len as usize] as u32, len as u32) as u16;
        next_code[len as usize] = next_code[len as usize].wrapping_add(1);
    }
}

