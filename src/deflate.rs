// ---------------------------------------------------------------------------
// adler32 (RFC 1950)
// ---------------------------------------------------------------------------

const ADLER_BASE: u32 = 65521;

fn adler32_update(adler: u32, data: &[u8]) -> u32 {
    let mut a = adler & 0xffff;
    let mut b = adler >> 16;
    for chunk in data.chunks(5552) {
        for &byte in chunk {
            a += byte as u32;
            b += a;
        }
        a %= ADLER_BASE;
        b %= ADLER_BASE;
    }
    (b << 16) | a
}

fn adler32(data: &[u8]) -> u32 {
    adler32_update(1, data)
}

