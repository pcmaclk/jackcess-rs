/// A `tree_desc` / `static_tree_desc` pair.
struct TreeParams<'a> {
    static_tree: Option<&'a [CtData]>,
    extra_bits: &'a [u8],
    extra_base: usize,
    elems: usize,
    max_length: usize,
}

struct TreeBuilder {
    heap: [usize; HEAP_SIZE],
    depth: [u8; HEAP_SIZE],
    bl_count: [u16; MAX_BITS + 1],
    heap_len: usize,
    heap_max: usize,
    opt_len: u64,
    static_len: u64,
}

impl TreeBuilder {
    fn new() -> TreeBuilder {
        TreeBuilder {
            heap: [0; HEAP_SIZE],
            depth: [0; HEAP_SIZE],
            bl_count: [0; MAX_BITS + 1],
            heap_len: 0,
            heap_max: 0,
            opt_len: 0,
            static_len: 0,
        }
    }

    /// `pqdownheap`.
    fn pqdownheap(&mut self, tree: &[CtData], mut k: usize) {
        let v = self.heap[k];
        let mut j = k << 1;
        while j <= self.heap_len {
            if j < self.heap_len && smaller(tree, self.heap[j + 1], self.heap[j], &self.depth) {
                j += 1;
            }
            if smaller(tree, v, self.heap[j], &self.depth) {
                break;
            }
            self.heap[k] = self.heap[j];
            k = j;
            j <<= 1;
        }
        self.heap[k] = v;
    }
}

/// `smaller`: compare two subtrees, using the tree depth as tie breaker.
fn smaller(tree: &[CtData], n: usize, m: usize, depth: &[u8]) -> bool {
    tree[n].freq < tree[m].freq || (tree[n].freq == tree[m].freq && depth[n] <= depth[m])
}

/// `gen_bitlen`: compute the optimal bit lengths and update `opt_len` /
/// `static_len`.
fn gen_bitlen(tb: &mut TreeBuilder, tree: &mut [CtData], params: &TreeParams, max_code: usize) {
    let max_length = params.max_length;
    tb.bl_count.fill(0);

    let root = tb.heap[tb.heap_max];
    tree[root].len = 0;

    let mut overflow: i32 = 0;
    let mut h = tb.heap_max + 1;
    while h < HEAP_SIZE {
        let n = tb.heap[h];
        let mut bits = tree[tree[n].dad as usize].len + 1;
        if bits > max_length as u16 {
            bits = max_length as u16;
            overflow += 1;
        }
        tree[n].len = bits;
        if n > max_code {
            h += 1;
            continue;
        }
        tb.bl_count[bits as usize] += 1;
        let xbits: u16 = if n >= params.extra_base {
            params.extra_bits[n - params.extra_base] as u16
        } else {
            0
        };
        let f = tree[n].freq as u64;
        tb.opt_len = tb.opt_len.wrapping_add(f * (bits as u64 + xbits as u64));
        if let Some(stree) = params.static_tree {
            tb.static_len = tb
                .static_len
                .wrapping_add(f * (stree[n].len as u64 + xbits as u64));
        }
        h += 1;
    }

    if overflow == 0 {
        return;
    }

    // Repair the bit length overflow: move one leaf down the tree, one overflow
    // item up as its brother.
    loop {
        let mut bits = max_length - 1;
        while tb.bl_count[bits] == 0 {
            bits -= 1;
        }
        tb.bl_count[bits] -= 1;
        tb.bl_count[bits + 1] += 2;
        tb.bl_count[max_length] -= 1;
        overflow -= 2;
        if overflow <= 0 {
            break;
        }
    }

    // Recompute all bit lengths, scanning in increasing frequency.
    let mut h = HEAP_SIZE;
    for bits in (1..=max_length).rev() {
        let mut n = tb.bl_count[bits];
        while n != 0 {
            h -= 1;
            let m = tb.heap[h];
            if m > max_code {
                continue;
            }
            if tree[m].len as usize != bits {
                tb.opt_len = tb.opt_len.wrapping_add(
                    (bits as u64).wrapping_sub(tree[m].len as u64) * tree[m].freq as u64,
                );
                tree[m].len = bits as u16;
            }
            n -= 1;
        }
    }
}

/// `build_tree`: construct one Huffman tree and generate the codes.
fn build_tree(tb: &mut TreeBuilder, tree: &mut [CtData], params: &TreeParams) -> usize {
    let elems = params.elems;
    let mut max_code: isize = -1;

    tb.heap_len = 0;
    tb.heap_max = HEAP_SIZE;
    for n in 0..elems {
        if tree[n].freq != 0 {
            tb.heap_len += 1;
            tb.heap[tb.heap_len] = n;
            max_code = n as isize;
            tb.depth[n] = 0;
        } else {
            tree[n].len = 0;
        }
    }

    // The pkzip format requires at least two codes of non zero frequency.
    while tb.heap_len < 2 {
        let node = if max_code < 2 {
            max_code += 1;
            max_code as usize
        } else {
            0
        };
        tb.heap_len += 1;
        tb.heap[tb.heap_len] = node;
        tree[node].freq = 1;
        tb.depth[node] = 0;
        tb.opt_len = tb.opt_len.wrapping_sub(1);
        if let Some(stree) = params.static_tree {
            tb.static_len = tb.static_len.wrapping_sub(stree[node].len as u64);
        }
    }
    let max_code = max_code as usize;

    // establish sub-heaps of increasing lengths
    let mut n = tb.heap_len / 2;
    while n >= 1 {
        tb.pqdownheap(tree, n);
        n -= 1;
    }

    // combine the least two frequent nodes
    let mut node = elems;
    loop {
        // pqremove
        let n = tb.heap[1];
        tb.heap[1] = tb.heap[tb.heap_len];
        tb.heap_len -= 1;
        tb.pqdownheap(tree, 1);

        let m = tb.heap[1];
        tb.heap_max -= 1;
        tb.heap[tb.heap_max] = n;
        tb.heap_max -= 1;
        tb.heap[tb.heap_max] = m;

        tree[node].freq = tree[n].freq + tree[m].freq;
        tb.depth[node] = if tb.depth[n] >= tb.depth[m] {
            tb.depth[n]
        } else {
            tb.depth[m]
        } + 1;
        tree[n].dad = node as u16;
        tree[m].dad = node as u16;

        tb.heap[1] = node;
        node += 1;
        tb.pqdownheap(tree, 1);

        if tb.heap_len < 2 {
            break;
        }
    }

    tb.heap_max -= 1;
    tb.heap[tb.heap_max] = tb.heap[1];

    gen_bitlen(tb, tree, params, max_code);
    gen_codes(tree, max_code, &tb.bl_count);
    max_code
}

/// `scan_tree`: count the bit length codes needed to send a tree.
fn scan_tree(bl_tree: &mut [CtData], tree: &mut [CtData], max_code: usize) {
    let mut prevlen: i32 = -1;
    let mut nextlen = tree[0].len as i32;
    let mut count: i32 = 0;
    let mut max_count: i32 = 7;
    let mut min_count: i32 = 4;

    if nextlen == 0 {
        max_count = 138;
        min_count = 3;
    }
    tree[max_code + 1].len = 0xffff; // guard

    for n in 0..=max_code {
        let curlen = nextlen;
        nextlen = tree[n + 1].len as i32;
        count += 1;
        if count < max_count && curlen == nextlen {
            continue;
        } else if count < min_count {
            bl_tree[curlen as usize].freq += count as u16;
        } else if curlen != 0 {
            if curlen != prevlen {
                bl_tree[curlen as usize].freq += 1;
            }
            bl_tree[REP_3_6].freq += 1;
        } else if count <= 10 {
            bl_tree[REPZ_3_10].freq += 1;
        } else {
            bl_tree[REPZ_11_138].freq += 1;
        }
        count = 0;
        prevlen = curlen;
        if nextlen == 0 {
            max_count = 138;
            min_count = 3;
        } else if curlen == nextlen {
            max_count = 6;
            min_count = 3;
        } else {
            max_count = 7;
            min_count = 4;
        }
    }
}

/// `send_tree`: send a literal or distance tree in compressed form.
fn send_tree(bw: &mut BitWriter, tree: &[CtData], max_code: usize, bl_tree: &[CtData]) {
    let mut prevlen: i32 = -1;
    let mut nextlen = tree[0].len as i32;
    let mut count: i32 = 0;
    let mut max_count: i32 = 7;
    let mut min_count: i32 = 4;

    if nextlen == 0 {
        max_count = 138;
        min_count = 3;
    }

    for n in 0..=max_code {
        let curlen = nextlen;
        nextlen = tree[n + 1].len as i32;
        count += 1;
        if count < max_count && curlen == nextlen {
            continue;
        } else if count < min_count {
            loop {
                bw.send_code(bl_tree, curlen as usize);
                count -= 1;
                if count == 0 {
                    break;
                }
            }
        } else if curlen != 0 {
            if curlen != prevlen {
                bw.send_code(bl_tree, curlen as usize);
                count -= 1;
            }
            bw.send_code(bl_tree, REP_3_6);
            bw.send_bits((count - 3) as u16, 2);
        } else if count <= 10 {
            bw.send_code(bl_tree, REPZ_3_10);
            bw.send_bits((count - 3) as u16, 3);
        } else {
            bw.send_code(bl_tree, REPZ_11_138);
            bw.send_bits((count - 11) as u16, 7);
        }
        count = 0;
        prevlen = curlen;
        if nextlen == 0 {
            max_count = 138;
            min_count = 3;
        } else if curlen == nextlen {
            max_count = 6;
            min_count = 3;
        } else {
            max_count = 7;
            min_count = 4;
        }
    }
}

/// `send_all_trees`.
fn send_all_trees(
    bw: &mut BitWriter,
    ltree: &[CtData],
    dtree: &[CtData],
    bl_tree: &[CtData],
    lcodes: usize,
    dcodes: usize,
    blcodes: usize,
) {
    bw.send_bits((lcodes - 257) as u16, 5);
    bw.send_bits((dcodes - 1) as u16, 5);
    bw.send_bits((blcodes - 4) as u16, 4);
    for rank in 0..blcodes {
        bw.send_bits(bl_tree[BL_ORDER[rank]].len, 3);
    }
    send_tree(bw, ltree, lcodes - 1, bl_tree);
    send_tree(bw, dtree, dcodes - 1, bl_tree);
}

/// `compress_block`.
fn compress_block(
    bw: &mut BitWriter,
    sym_buf: &[u8],
    ltree: &[CtData],
    dtree: &[CtData],
    t: &StaticTables,
) {
    let mut sx = 0usize;
    while sx < sym_buf.len() {
        let dist = sym_buf[sx] as usize + ((sym_buf[sx + 1] as usize) << 8);
        let lc = sym_buf[sx + 2] as usize;
        sx += 3;

        if dist == 0 {
            bw.send_code(ltree, lc);
        } else {
            let code = t.length_code[lc] as usize;
            bw.send_code(ltree, code + LITERALS + 1);
            let extra = EXTRA_LBITS[code];
            let mut extra_lc = lc;
            if extra != 0 {
                extra_lc -= t.base_length[code] as usize;
                bw.send_bits(extra_lc as u16, extra as u32);
            }
            let mut dist1 = dist - 1;
            let dcode = t.d_code(dist1);
            bw.send_code(dtree, dcode);
            let dextra = EXTRA_DBITS[dcode];
            if dextra != 0 {
                dist1 -= t.base_dist[dcode] as usize;
                bw.send_bits(dist1 as u16, dextra as u32);
            }
        }
    }
    bw.send_code(ltree, END_BLOCK);
}

