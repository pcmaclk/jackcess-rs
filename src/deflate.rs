//! Port of the zlib deflate/inflate needed by attachment columns.
//!
//! Jackcess compresses attachment payloads whose file type Access does not
//! store raw with `new Deflater(3)` inside a `DeflaterOutputStream`, i.e. a
//! zlib stream (RFC 1950/1951) at level 3.  Byte-identical output requires a
//! faithful port of zlib's deflate at that level, so this module follows
//! zlib 1.3.1 `deflate.c` / `trees.c` closely:
//!
//! * level 3 selects `deflate_fast` with `good_length=4`, `max_lazy=6`,
//!   `nice_length=32`, `max_chain=32` (zlib's `configuration_table`), a 32K
//!   window, `memLevel=8` (16K symbols per block, 15 bit hash with a 5 bit
//!   shift), and the `deflate_fast` emit/insert rules;
//! * blocks are closed when the symbol buffer holds 16383 symbols and are
//!   emitted as stored, static-Huffman or dynamic-Huffman blocks using zlib's
//!   own cost estimate and tie-breaking;
//! * the dynamic Huffman trees are built with zlib's heap (`smaller` uses the
//!   tree depth as tie breaker), `gen_bitlen` overflow repair, `scan_tree` /
//!   `send_tree` run-length encoding and `bl_order` emission order.
//!
//! `zlib_compress` produces the bytes of
//! `new DeflaterOutputStream(out, new Deflater(3))` (default 512 byte buffer,
//! `nowrap=false`), including the `0x78 0x5e` zlib header and the big-endian
//! adler32 trailer.  The reference bytes live in
//! `resources/attach_ref/deflate_corpus.bin`, generated by
//! `java-src/AttachOracle.java`; the unit tests at the bottom of this file
//! compare every corpus entry byte for byte.
//!
//! `zlib_decompress` inflates arbitrary zlib streams (stored, fixed and
//! dynamic blocks, with or without a preset dictionary marker) and verifies the
//! adler32 trailer.

use crate::error::{Error, Result};
use std::sync::OnceLock;

/// Compresses `data` into a zlib stream exactly as
/// `java.util.zip.DeflaterOutputStream` with `new Deflater(3)` does.
pub fn zlib_compress(data: &[u8]) -> Result<Vec<u8>> {
    Ok(compress(data))
}

/// Decompresses a zlib stream (needed to read attachments written by Access).
pub fn zlib_decompress(data: &[u8]) -> Result<Vec<u8>> {
    inflate(data)
}

