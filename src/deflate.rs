// the deflate state and the level 3 (`deflate_fast`) driver
// ---------------------------------------------------------------------------

struct DeflateState<'a> {
    input: &'a [u8],
    in_pos: usize,
    window: Vec<u8>,
    head: Vec<u16>,
    prev: Vec<u16>,
    strstart: usize,
    lookahead: usize,
    match_start: usize,
    match_length: usize,
    prev_length: usize,
    ins_h: usize,
    /// start of the current block in the window; negative once the block start
    /// has slid out of the window (zlib's `long block_start`)
    block_start: i64,
    insert: usize,
    adler: u32,
    matches: usize,
    tb: TreeBuilder,
    dyn_ltree: Vec<CtData>,
    dyn_dtree: Vec<CtData>,
    bl_tree: Vec<CtData>,
    l_max_code: usize,
    d_max_code: usize,
    sym_buf: Vec<u8>,
    bw: BitWriter,
}

impl<'a> DeflateState<'a> {
    fn new(input: &'a [u8]) -> DeflateState<'a> {
        let mut st = DeflateState {
            input,
            in_pos: 0,
            // zlib's window is exactly two windows; the extra MAX_MATCH bytes
            // keep the few look-ahead reads inside the allocation (zlib relies
            // on its zeroed high water mark there, and so do we: the bytes stay
            // zero and matches are clamped to the lookahead)
            window: vec![0; WINDOW_SIZE + MAX_MATCH],
            head: vec![0; HASH_SIZE],
            prev: vec![0; W_SIZE],
            strstart: 0,
            lookahead: 0,
            match_start: 0,
            match_length: MIN_MATCH - 1,
            prev_length: MIN_MATCH - 1,
            ins_h: 0,
            block_start: 0,
            insert: 0,
            adler: 1,
            matches: 0,
            tb: TreeBuilder::new(),
            dyn_ltree: vec![CtData::default(); HEAP_SIZE],
            dyn_dtree: vec![CtData::default(); 2 * D_CODES + 1],
            bl_tree: vec![CtData::default(); 2 * BL_CODES + 1],
            l_max_code: 0,
            d_max_code: 0,
            sym_buf: Vec::with_capacity(SYM_END + 3),
            bw: BitWriter::new(),
        };
        st.init_block();
        st
    }

    /// `init_block`.
    fn init_block(&mut self) {
        for t in self.dyn_ltree.iter_mut() {
            t.freq = 0;
        }
        for t in self.dyn_dtree.iter_mut() {
            t.freq = 0;
        }
        for t in self.bl_tree.iter_mut() {
            t.freq = 0;
        }
        self.dyn_ltree[END_BLOCK].freq = 1;
        self.tb.opt_len = 0;
        self.tb.static_len = 0;
        self.sym_buf.clear();
        self.matches = 0;
    }

    /// `INSERT_STRING`: insert `str` in the dictionary, return the previous head
    /// of its hash chain.
    fn insert_string(&mut self, str: usize) -> usize {
        self.ins_h =
            ((self.ins_h << HASH_SHIFT) ^ self.window[str + MIN_MATCH - 1] as usize) & HASH_MASK;
        let head = self.head[self.ins_h] as usize;
        self.prev[str & W_MASK] = self.head[self.ins_h];
        self.head[self.ins_h] = str as u16;
        head
    }

    /// `slide_hash`.
    fn slide_hash(&mut self) {
        for h in self.head.iter_mut() {
            *h = if (*h as usize) >= W_SIZE {
                *h - W_SIZE as u16
            } else {
                0
            };
        }
        for p in self.prev.iter_mut() {
            *p = if (*p as usize) >= W_SIZE {
                *p - W_SIZE as u16
            } else {
                0
            };
        }
    }

    /// `fill_window`.
    fn fill_window(&mut self) {
        loop {
            let mut more = WINDOW_SIZE - self.lookahead - self.strstart;

            if self.strstart >= W_SIZE + MAX_DIST {
                // move the upper half to the lower one
                let len = W_SIZE - more;
                self.window.copy_within(W_SIZE..W_SIZE + len, 0);
                self.match_start = self.match_start.wrapping_sub(W_SIZE);
                self.strstart -= W_SIZE;
                self.block_start -= W_SIZE as i64;
                if self.insert > self.strstart {
                    self.insert = self.strstart;
                }
                self.slide_hash();
                more += W_SIZE;
            }
            if self.in_pos >= self.input.len() {
                break;
            }

            let n = more.min(self.input.len() - self.in_pos);
            let dst = self.strstart + self.lookahead;
            self.window[dst..dst + n].copy_from_slice(&self.input[self.in_pos..self.in_pos + n]);
            self.adler = adler32_update(self.adler, &self.input[self.in_pos..self.in_pos + n]);
            self.in_pos += n;
            self.lookahead += n;

            // Initialize the hash value now that we have some input.  This
            // seeds `ins_h` with the first two bytes of the current string;
            // `INSERT_STRING` then completes the three byte hash.  Without the
            // seed the first hash chains of a stream would differ.
            if self.lookahead + self.insert >= MIN_MATCH {
                let str = self.strstart - self.insert;
                self.ins_h = self.window[str] as usize;
                self.ins_h =
                    ((self.ins_h << HASH_SHIFT) ^ self.window[str + 1] as usize) & HASH_MASK;
            }

            if self.lookahead >= MIN_LOOKAHEAD {
                break;
            }
        }
    }

    /// `longest_match`: the best match for the string at `strstart` in the hash
    /// chain starting at `cur_match`.
    ///
    /// The comparison is bounded by the lookahead instead of zlib's window scan
    /// (`strend`): zlib clamps every returned length to the lookahead, and any
    /// candidate which would run past it reaches `nice_match` (which is itself
    /// clamped to the lookahead) and ends the search, so the result and the
    /// chosen `match_start` are identical.
    fn longest_match(&mut self, mut cur_match: usize) -> usize {
        let mut chain_length = MAX_CHAIN;
        let mut best_len = self.prev_length;
        let mut nice_match = NICE_MATCH;
        let limit = self.strstart.saturating_sub(MAX_DIST);
        let lookahead = self.lookahead;

        if best_len >= 4 {
            // configuration_table[3].good_length, never reached by deflate_fast
            chain_length >>= 2;
        }
        if nice_match > lookahead {
            nice_match = lookahead;
        }

        let max_len = MAX_MATCH.min(lookahead);
        let scan = self.strstart;
        loop {
            let mut len = 0usize;
            while len < max_len && self.window[scan + len] == self.window[cur_match + len] {
                len += 1;
            }
            if len > best_len {
                self.match_start = cur_match;
                best_len = len;
                if len >= nice_match {
                    break;
                }
            }
            cur_match = self.prev[cur_match & W_MASK] as usize;
            if cur_match <= limit {
                break;
            }
            chain_length -= 1;
            if chain_length == 0 {
                break;
            }
        }

        if best_len <= lookahead {
            best_len
        } else {
            lookahead
        }
    }

    /// `_tr_tally_lit`: save a literal and tally its frequency.
    fn tally_lit(&mut self, lc: u8) -> bool {
        self.sym_buf.push(0);
        self.sym_buf.push(0);
        self.sym_buf.push(lc);
        self.dyn_ltree[lc as usize].freq += 1;
        self.sym_buf.len() == SYM_END
    }

    /// `_tr_tally_dist`: save a match and tally its frequencies.
    fn tally_dist(&mut self, dist: usize, lc: usize) -> bool {
        let t = static_tables();
        self.sym_buf.push(dist as u8);
        self.sym_buf.push((dist >> 8) as u8);
        self.sym_buf.push(lc as u8);
        self.matches += 1;
        let dist1 = dist - 1;
        let code = t.length_code[lc] as usize;
        self.dyn_ltree[code + LITERALS + 1].freq += 1;
        let dcode = t.d_code(dist1);
        self.dyn_dtree[dcode].freq += 1;
        self.sym_buf.len() == SYM_END
    }

    /// `build_bl_tree`: build the bit length tree, return the index in
    /// `bl_order` of the last bit length code to send.
    fn build_bl_tree(&mut self) -> usize {
        let l_max_code = self.l_max_code;
        let d_max_code = self.d_max_code;
        scan_tree(&mut self.bl_tree, &mut self.dyn_ltree, l_max_code);
        scan_tree(&mut self.bl_tree, &mut self.dyn_dtree, d_max_code);

        let bl_desc = TreeParams {
            static_tree: None,
            extra_bits: &EXTRA_BLBITS,
            extra_base: 0,
            elems: BL_CODES,
            max_length: MAX_BL_BITS,
        };
        build_tree(&mut self.tb, &mut self.bl_tree, &bl_desc);

        let mut max_blindex = BL_CODES - 1;
        while max_blindex >= 3 {
            if self.bl_tree[BL_ORDER[max_blindex]].len != 0 {
                break;
            }
            max_blindex -= 1;
        }
        self.tb.opt_len = self
            .tb
            .opt_len
            .wrapping_add(3 * (max_blindex as u64 + 1) + 5 + 5 + 4);
        max_blindex
    }

    /// `_tr_flush_block`.
    fn flush_block(&mut self, t: &StaticTables, last: bool) {
        let stored_len = (self.strstart as i64 - self.block_start) as u64;
        let buf_ok = self.block_start >= 0;

        let l_desc = TreeParams {
            static_tree: Some(&t.static_ltree[..]),
            extra_bits: &EXTRA_LBITS,
            extra_base: LITERALS + 1,
            elems: L_CODES,
            max_length: MAX_BITS,
        };
        let d_desc = TreeParams {
            static_tree: Some(&t.static_dtree[..]),
            extra_bits: &EXTRA_DBITS,
            extra_base: 0,
            elems: D_CODES,
            max_length: MAX_BITS,
        };

        self.l_max_code = build_tree(&mut self.tb, &mut self.dyn_ltree, &l_desc);
        self.d_max_code = build_tree(&mut self.tb, &mut self.dyn_dtree, &d_desc);
        let max_blindex = self.build_bl_tree();

        let mut opt_lenb = (self.tb.opt_len.wrapping_add(3).wrapping_add(7)) >> 3;
        let static_lenb = (self.tb.static_len.wrapping_add(3).wrapping_add(7)) >> 3;
        if static_lenb <= opt_lenb {
            opt_lenb = static_lenb;
        }

        if stored_len + 4 <= opt_lenb && buf_ok {
            // emit a stored block
            self.bw.send_bits((STORED_BLOCK << 1) | (last as u16), 3);
            self.bw.bi_windup();
            self.bw.put_short(stored_len as u16);
            self.bw.put_short(!(stored_len as u16));
            let start = self.block_start as usize;
            let end = start + stored_len as usize;
            self.bw.out.extend_from_slice(&self.window[start..end]);
        } else if static_lenb == opt_lenb {
            self.bw.send_bits((STATIC_TREES << 1) | (last as u16), 3);
            compress_block(
                &mut self.bw,
                &self.sym_buf,
                &t.static_ltree,
                &t.static_dtree,
                t,
            );
        } else {
            self.bw.send_bits((DYN_TREES << 1) | (last as u16), 3);
            send_all_trees(
                &mut self.bw,
                &self.dyn_ltree,
                &self.dyn_dtree,
                &self.bl_tree,
                self.l_max_code + 1,
                self.d_max_code + 1,
                max_blindex + 1,
            );
            compress_block(
                &mut self.bw,
                &self.sym_buf,
                &self.dyn_ltree,
                &self.dyn_dtree,
                t,
            );
        }

        self.init_block();
        if last {
            self.bw.bi_windup();
        }
    }

    /// `deflate_fast` for the whole input, with a finish at the end.
    fn deflate_fast(&mut self, t: &StaticTables) {
        loop {
            if self.lookahead < MIN_LOOKAHEAD {
                self.fill_window();
                if self.lookahead == 0 {
                    break;
                }
            }

            let mut hash_head = 0usize;
            if self.lookahead >= MIN_MATCH {
                hash_head = self.insert_string(self.strstart);
            }

            if hash_head != 0 && self.strstart - hash_head <= MAX_DIST {
                self.match_length = self.longest_match(hash_head);
            }

            let bflush;
            if self.match_length >= MIN_MATCH {
                let dist = self.strstart - self.match_start;
                bflush = self.tally_dist(dist, self.match_length - MIN_MATCH);
                self.lookahead -= self.match_length;

                if self.match_length <= MAX_INSERT_LENGTH && self.lookahead >= MIN_MATCH {
                    // insert the strings of the match in the hash table
                    self.match_length -= 1;
                    loop {
                        self.strstart += 1;
                        self.insert_string(self.strstart);
                        self.match_length -= 1;
                        if self.match_length == 0 {
                            break;
                        }
                    }
                    self.strstart += 1;
                } else {
                    self.strstart += self.match_length;
                    self.match_length = 0;
                    self.ins_h = self.window[self.strstart] as usize;
                    self.ins_h = ((self.ins_h << HASH_SHIFT)
                        ^ self.window[self.strstart + 1] as usize)
                        & HASH_MASK;
                }
            } else {
                let lit = self.window[self.strstart];
                bflush = self.tally_lit(lit);
                self.lookahead -= 1;
                self.strstart += 1;
            }

            if bflush {
                self.flush_block(t, false);
                self.block_start = self.strstart as i64;
            }
        }

        self.insert = if self.strstart < MIN_MATCH - 1 {
            self.strstart
        } else {
            MIN_MATCH - 1
        };
        self.flush_block(t, true);
    }
}

fn compress(data: &[u8]) -> Vec<u8> {
    let t = static_tables();
    let mut st = DeflateState::new(data);

    // zlib header: CM=8, CINFO=7, FLEVEL=1 (level 3), FDICT=0, FCHECK
    // chosen so that (0x78 << 8 | flg) % 31 == 0 -> 0x78 0x5e
    let header: u32 = (8 + ((W_BITS as u32 - 8) << 4)) << 8;
    let mut hdr = header | (1 << 6);
    hdr += 31 - (hdr % 31);
    st.bw.put_byte((hdr >> 8) as u8);
    st.bw.put_byte(hdr as u8);

    st.deflate_fast(t);

    // adler32 trailer, big endian
    let adler = st.adler;
    st.bw.put_byte((adler >> 24) as u8);
    st.bw.put_byte((adler >> 16) as u8);
    st.bw.put_byte((adler >> 8) as u8);
    st.bw.put_byte(adler as u8);

    st.bw.out
}

